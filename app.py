TOKENS = {"access_token": None, "refresh_token": None, "expires_at": 0, "email": None}
_device = {"device_code": None, "interval": 5, "active": False, "error": None}
_lock = threading.Lock()


# ── .env persistence (no extra deps) ──────────────────────────────────────────
def load_env():
    if not os.path.exists(ENV_PATH):
        return {}
    data = {}
    with open(ENV_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            data[k.strip()] = v.strip()
    return data


def save_env():
    lines = [
        "# OneDrive API tokens — auto-managed, do not share.",
        f"ACCESS_TOKEN={TOKENS['access_token'] or ''}",
        f"REFRESH_TOKEN={TOKENS['refresh_token'] or ''}",
        f"EXPIRES_AT={int(TOKENS['expires_at'])}",
        f"EMAIL={TOKENS['email'] or ''}",
    ]
    try:
        with open(ENV_PATH, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    except OSError:
        pass  # read-only FS (Wasmer): the token lives in memory + token.yml, .env is optional


# ── Token helpers ─────────────────────────────────────────────────────────────
REFRESH_ERR = {"msg": None}


def apply_token_response(res):
    """Store a token endpoint response. Returns True on success."""
    if "access_token" not in res:
        return False
    with _lock:
        TOKENS["access_token"] = res["access_token"]
        # refresh tokens rotate — keep the newest, fall back to the old one
        if res.get("refresh_token"):
            TOKENS["refresh_token"] = res["refresh_token"]
        TOKENS["expires_at"] = time.time() + int(res.get("expires_in", 3600))
    fetch_email()
    save_env()
    return True


def refresh_now():
    """Use the refresh token to mint a fresh access token."""
    rt = TOKENS.get("refresh_token")
    if not rt:
        return False
    try:
        res = S.post(f"{AUTH_BASE}/token", data={
            "client_id": CLIENT_ID,
            "grant_type": "refresh_token",
            "refresh_token": rt,
            "scope": SCOPES,
        }, timeout=20).json()
    except Exception as e:
        REFRESH_ERR["msg"] = f"network/SSL error contacting Microsoft: {e}"
        print(f"[refresh] {REFRESH_ERR['msg']}")
        return False
    if not apply_token_response(res):
        REFRESH_ERR["msg"] = res.get("error_description") or str(res)
        print(f"[refresh] failed: {REFRESH_ERR['msg']}")
        return False
    REFRESH_ERR["msg"] = None
    print(f"[refresh] token refreshed, valid until {time.strftime('%H:%M:%S', time.localtime(TOKENS['expires_at']))}")
    return True


def valid_token():
    """Return a non-expired access token, minting one from the refresh token when needed.
    Must refresh when the access token is MISSING (fresh WSGI/cold start never ran main()'s
    startup refresh) — not only when it's near expiry — or Graph gets `Bearer None`."""
    if not TOKENS.get("refresh_token"):
        return None
    if not TOKENS["access_token"] or time.time() > TOKENS["expires_at"] - 120:
        refresh_now()
    return TOKENS["access_token"]


def fetch_email():
    try:
        me = S.get(
            f"{GRAPH}/me?$select=userPrincipalName,displayName",
            headers={"Authorization": f"Bearer {TOKENS['access_token']}"}, timeout=15,
        ).json()
        TOKENS["email"] = me.get("userPrincipalName") or me.get("displayName")
    except Exception:
        pass


def refresher_loop():
    while True:
        time.sleep(REFRESH_EVERY)
        if TOKENS.get("refresh_token"):
            refresh_now()


# ── Graph request helpers ─────────────────────────────────────────────────────
def H():
    return {"Authorization": f"Bearer {valid_token()}"}


def _token_err():
    return ("Could not get a Microsoft access token. "
            + (REFRESH_ERR["msg"] or "The stored refresh token may be invalid — reconnect the account."))


# Graph throttles hard on bursts (a 25-file upload trips it at ~20 createUploadSession
# calls) and answers 429 + Retry-After. Every Graph call goes through this so one throttled
# response is a short wait, not a lost file.
GRAPH_RETRIES = 4
RETRY_STATUS = (429, 500, 502, 503, 504)


def retry_after(resp, attempt):
    """Seconds to wait, preferring Graph's own hint; capped so a request can't hang forever."""
    hint = resp.headers.get("Retry-After")
    if hint:
        try:
            return min(float(hint), 20.0)
        except ValueError:
            pass
    try:
        body = resp.json()
        secs = (body.get("error") or {}).get("retryAfterSeconds")
        if secs:
            return min(float(secs), 20.0)
    except Exception:
        pass
    return min(0.5 * (2 ** attempt), 8.0)   # exponential backoff fallback


def graph_req(method, path, *, retries=GRAPH_RETRIES, **kw):
    """One Graph request with throttle-aware retries. Returns the final Response."""
    url = path if path.startswith("http") else f"{GRAPH}{path}"
    kw.setdefault("timeout", 30)
    extra = kw.pop("_headers", None) or {}   # popped once: retries must keep Content-Type
    resp = None
    for attempt in range(retries + 1):
        resp = S.request(method, url, headers={**H(), **extra}, **kw)
        if resp.status_code not in RETRY_STATUS or attempt == retries:
            return resp
        wait = retry_after(resp, attempt)
        print(f"[graph] {method} {path} -> {resp.status_code}, retrying in {wait:.1f}s "
              f"({attempt + 1}/{retries})")
        time.sleep(wait)
    return resp


def _json(resp):
    try:
        return resp.json()
    except ValueError:
        return {"error": {"code": str(resp.status_code),
                          "message": (resp.text or "non-JSON response")[:200]}}


def gh(path):
    if not valid_token():
        return {"error": {"message": _token_err()}}
    return _json(graph_req("GET", path))


def gd(path):
    return graph_req("DELETE", path)


def gpost(path, body=None):
    return _json(graph_req("POST", path, _headers={"Content-Type": "application/json"},
                           json=body))


def gput(path, data, content_type="application/octet-stream"):
    return _json(graph_req("PUT", path, _headers={"Content-Type": content_type}, data=data,
                           timeout=300))


def gpatch(path, body=None):
    return _json(graph_req("PATCH", path, _headers={"Content-Type": "application/json"},
                           json=body))


def signed_url(item_id):
    data = gh(f"/me/drive/items/{item_id}")
    if "error" in data:
        return None, data["error"].get("message", "Graph error")
    url = data.get("@microsoft.graph.downloadUrl")
    if not url:
        return None, "No download URL (folder or vault item)"
    return url, None


# ── Device-code auth flow ─────────────────────────────────────────────────────
def poll_device(device_code, interval):
    """Background: poll Microsoft until the user finishes the browser login."""
    _device["active"] = True
    _device["error"] = None
    while _device["active"]:
        time.sleep(interval)
        try:
            res = S.post(f"{AUTH_BASE}/token", data={
                "grant_type": "urn:ietf:params:oauth:grant-type:device_code",
                "device_code": device_code,
                "client_id": CLIENT_ID,
            }, timeout=20).json()
        except Exception:
            continue
        if "access_token" in res:
            apply_token_response(res)
            _device["active"] = False
            print(f"[auth] connected as {TOKENS.get('email')}")
            return
        err = res.get("error")
        if err == "authorization_pending":
            continue
        if err == "slow_down":
            interval += 5
            continue
        # authorization_declined / expired_token / bad_verification_code
        _device["error"] = res.get("error_description", err)
        _device["active"] = False
        return


