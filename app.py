def boot():
    """Load persisted tokens + start the refresher. Runs on import (for gunicorn/Wasmer) and main()."""
    global _booted
    if _booted:
        return
    _booted = True
    # Canonical: token.yml (multi-account). basic entries are usable now; secure entries stay
    # locked until the browser posts decrypted tokens to /api/unlock.
    load_accounts()
