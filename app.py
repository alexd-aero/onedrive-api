# ── GitOps config: creds.yml + token.yml (committed to the repo) ───────────────
# The app is configured by two files in this dir. On ephemeral hosts (Wasmer) they can't be
# written at runtime, so setup emits a "code" the user pastes into the file + commits. Locally
# we also write them directly for convenience. Format: a YAML file with one `data: <b64(json)>`.
_DIR       = os.path.dirname(os.path.abspath(__file__))
CREDS_PATH = os.path.join(_DIR, "creds.yml")
TOKEN_PATH = os.path.join(_DIR, "token.yml")


def _b64d(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def _b64e(b):
    return base64.urlsafe_b64encode(b).decode().rstrip("=")


def _read_yml_blob(path):
    if not os.path.exists(path):
        return None
    try:
        text = open(path, encoding="utf-8").read()
        m = re.search(r"data:\s*(.+)", text, re.S)   # everything after the first `data:`
        if not m:
            return None
        # Strip anything a paste/editor might inject (wrapping, whitespace, quotes); keep only
        # base64url chars. This makes "already configured?" detection robust so a redeploy never
        # bounces a done step back to setup.
        raw = re.sub(r"[^A-Za-z0-9_\-]", "", m.group(1))
        if not raw or "PASTE" in raw.upper():
            return None
        return json.loads(_b64d(raw).decode())
    except Exception as e:
        print(f"[config] could not parse {os.path.basename(path)}: {e}")
    return None


def make_yml(blob, kind):
    raw = _b64e(json.dumps(blob, separators=(",", ":")).encode())
    return (f"# onedrive-api {kind} — generated by setup.\n"
            f"# Replace this ENTIRE file with the copied code, commit, and redeploy.\n"
            f"# Keep this file private (never make the repo public).\n"
            f"data: {raw}\n")


def try_write(path, content):
    """Write config locally when the filesystem allows it (local dev). Silent on read-only hosts."""
    try:
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return True
    except Exception:
        return False


CREDS    = _read_yml_blob(CREDS_PATH)   # {v,method,user,salt,iters,phash,sess,enc_salt?}
TOKENCFG = _read_yml_blob(TOKEN_PATH)   # basic:{method,rt}  secure:{method,enc_salt,iters,iv,ct}

# session-signing secret: from creds (stable across restarts) else ephemeral
SESSION_SECRET = ((CREDS or {}).get("sess") or secrets.token_hex(24)).encode()
# in-memory unlock flag for secure mode (token decrypted client-side, POSTed after login)
_UNLOCKED = {"ok": False}


def pbkdf2(password, salt_b64, iters):
    return _b64e(hashlib.pbkdf2_hmac("sha256", password.encode(), _b64d(salt_b64), iters))


def sign_session(user, hours=720):
    payload = _b64e(json.dumps({"u": user, "exp": int(time.time()) + hours * 3600}).encode())
    sig = hmac.new(SESSION_SECRET, payload.encode(), hashlib.sha256).hexdigest()[:32]
    return payload + "." + sig


def valid_session(cookie):
    if not cookie or "." not in cookie:
        return None
    payload, sig = cookie.rsplit(".", 1)
    good = hmac.new(SESSION_SECRET, payload.encode(), hashlib.sha256).hexdigest()[:32]
    if not hmac.compare_digest(sig, good):
        return None
    try:
        d = json.loads(_b64d(payload).decode())
        return d.get("u") if d.get("exp", 0) > time.time() else None
    except Exception:
        return None


def app_state():
    """unconfigured -> setup ; creds_only -> connect ; ready -> app."""
    if CREDS is None:
        return "unconfigured"
    if TOKENCFG is None:
        return "creds_only"
    return "ready"


def is_authed():
    return valid_session(request.cookies.get("od_sess")) is not None


# ── Multi-account ─────────────────────────────────────────────────────────────
# token.yml holds a list of accounts; basic entries carry the refresh token, secure entries
# carry its AES-GCM ciphertext. The ACTIVE account is a per-runtime choice (switching does NOT
# rewrite token.yml — only add/remove do), so switching accounts never needs a commit.
ACCOUNTS = []          # [{"id":.., "email":..}] for the UI
RT_STORE = {}          # id -> refresh_token (basic: from file at boot; secure: after unlock)
ACTIVE   = {"id": None}


def _account_entries(cfg):
    """Normalize token.yml into a list of account entries (handles the old single-account format)."""
    if not cfg:
        return []
    if isinstance(cfg.get("accounts"), list):
        return cfg["accounts"]
    e = {"id": "acct1", "email": cfg.get("email", "")}
    if cfg.get("method") == "basic" and cfg.get("rt"):
        e["rt"] = cfg["rt"]; return [e]
    if cfg.get("method") == "secure" and cfg.get("ct"):
        e.update({"iv": cfg["iv"], "ct": cfg["ct"]}); return [e]
    return []


def build_token_blob(entries):
    b = {"method": CREDS["method"], "accounts": entries}
    if CREDS and CREDS.get("method") == "secure":
        b["enc_salt"] = CREDS["enc_salt"]; b["iters"] = CREDS["iters"]
    return b


def load_accounts():
    ACCOUNTS.clear()
    for e in _account_entries(TOKENCFG):
        ACCOUNTS.append({"id": e["id"], "email": e.get("email", "")})
        if e.get("rt"):                       # basic: usable immediately
            RT_STORE[e["id"]] = e["rt"]
    if ACCOUNTS and (ACTIVE["id"] not in {a["id"] for a in ACCOUNTS}):
        set_active(ACCOUNTS[0]["id"])


def set_active(aid):
    ACTIVE["id"] = aid
    if aid in RT_STORE:
        with _lock:
            TOKENS["refresh_token"] = RT_STORE[aid]
            TOKENS["expires_at"] = 0
            TOKENS["access_token"] = None
        TOKENS["email"] = next((a["email"] for a in ACCOUNTS if a["id"] == aid), None)
        return True
    return False


def token_available():
    """True when the active account has a usable refresh token (basic: file; secure: after unlock)."""
    return bool(ACTIVE["id"] and RT_STORE.get(ACTIVE["id"]))


def require_auth(fn):
    @functools.wraps(fn)
    def wrap(*a, **k):
        if CREDS is None:
            return jsonify({"error": "not configured"}), 403
        if not is_authed():
            return jsonify({"error": "unauthorized"}), 401
        return fn(*a, **k)
    return wrap


